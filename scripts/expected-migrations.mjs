#!/usr/bin/env node
/**
 * Writes api/_lib/expected-migrations.ts: every admin-DB migration in this repo, with the same
 * SHA-256 migrate.sh records. The deployed site compares it with what each database says it has
 * applied (api.schema_status), so a migration that was merged but never applied raises an alert.
 *
 *   node scripts/expected-migrations.mjs           regenerate
 *   node scripts/expected-migrations.mjs --check   CI: fail if the file is out of date
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const out = new URL("api/_lib/expected-migrations.ts", root);

export function collect(dbDir) {
  return readdirSync(dbDir).filter((f) => /^\d{4}_[a-z0-9_]+\.sql$/.test(f)).sort().map((f) => ({
    version: f.replace(/\.sql$/, ""),
    checksum: createHash("sha256").update(readFileSync(new URL(f, dbDir))).digest("hex"),
  }));
}

export function source(lists) {
  const body = Object.entries(lists).map(([db, ms]) =>
    `  ${db}: [\n${ms.map((m) => `    { version: "${m.version}", checksum: "${m.checksum}" },`).join("\n")}\n  ],`).join("\n");
  return [
    "/**",
    " * Generated by scripts/expected-migrations.mjs: do not edit. Every admin-DB migration in this",
    " * repo and its SHA-256 (as migrate.sh records it). CI fails if this is out of date.",
    " */",
    "export type Expected = { version: string; checksum: string };",
    "export const EXPECTED_MIGRATIONS: { app_admin: Expected[]; portal_admin: Expected[] } = {",
    body,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = source({
    app_admin: collect(new URL("db/admin-db/app_admin/", root)),
    portal_admin: collect(new URL("db/admin-db/portal_admin/", root)),
  });
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(out, "utf8"); } catch { /* missing: reported below */ }
    if (current !== text) {
      console.error("expected-migrations: api/_lib/expected-migrations.ts is out of date. Run: node scripts/expected-migrations.mjs");
      process.exit(1);
    }
    console.log("expected-migrations: up to date");
  } else {
    writeFileSync(out, text);
    console.log("expected-migrations: written");
  }
}
